// Synthetic isolated lab only. Bearer URLs are never printed or persisted here.
const assert = require('node:assert/strict');
const cp = require('node:child_process');
const { chromium } = require('playwright');
const base = process.env.MAPOS_LAB_URL || 'http://127.0.0.1:8231';
assert(['127.0.0.1', 'localhost', '[::1]'].includes(new URL(base).hostname));
const container = 'mapos5-portal-cliente-lab-php';
cp.execFileSync('docker', ['exec', container, 'php', '-d', 'variables_order=EGPCS', '/var/www/html/tests/Support/portal_cliente_publico.php'], { stdio: 'ignore' });
const fixture = JSON.parse(cp.execFileSync('docker', ['exec', container, 'php', '-r', "echo file_get_contents('/lab/portal-cliente-private.json');"], { encoding: 'utf8' }));
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
    const page = await context.newPage();
    let response = await page.goto(`${base}/index.php/publico_cliente/index/${fixture.a}`);
    assert.equal(response.status(), 200, 'valid customer link must open');
    assert.match(response.headers()['cache-control'] || '', /no-store/i);
    assert.equal(response.headers()['referrer-policy'], 'no-referrer');
    const postPublico = await context.request.post(`${base}/index.php/publico_cliente/index/${fixture.a}`);
    assert.ok([403, 404, 405].includes(postPublico.status()), 'public portal rejects POST');
    assert.match(await page.locator('body').innerText(), /Cliente Alfa Sintetico/);
    assert.doesNotMatch(await page.locator('body').innerText(), /PRIVADO-BETA|Equipamento Beta Sintetico/);
    if (process.env.PORTAL_SCREENSHOT_DIR) {
      const fs = require('node:fs');
      const path = require('node:path');
      fs.mkdirSync(process.env.PORTAL_SCREENSHOT_DIR, { recursive: true });
      await page.screenshot({ path: path.join(process.env.PORTAL_SCREENSHOT_DIR, 'portal-desktop.png') });
      const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 1 });
      const mobilePage = await mobile.newPage();
      assert.equal((await mobilePage.goto(`${base}/index.php/publico_cliente/index/${fixture.a}`)).status(), 200);
      assert.equal(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'mobile has no horizontal overflow');
      assert.ok((await mobilePage.locator('nav[aria-label="Filtrar ordens"] a').evaluateAll(links => links.every(link => link.getBoundingClientRect().height >= 44))), 'filter touch targets are at least 44px tall');
      await mobilePage.screenshot({ path: path.join(process.env.PORTAL_SCREENSHOT_DIR, 'portal-mobile.png') });
      await mobile.close();
    }
    let texto = await page.locator('body').innerText();
    assert.match(texto, /R\$ 600,00/);
    assert.match(texto, /R\$ 350,00/);
    assert.match(texto, /R\$ 250,00/);
    response = await page.goto(`${base}/index.php/publico_cliente/index/${fixture.a}?filtro=pendente`);
    texto = await page.locator('body').innerText();
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[0]}\\b`));
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[1]}\\b`));
    assert.doesNotMatch(texto, new RegExp(`OS #${fixture.ordensA[11]}\\b`));
    response = await page.goto(`${base}/index.php/publico_cliente/index/${fixture.a}?filtro=entregue`);
    texto = await page.locator('body').innerText();
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[1]}\\b`));
    assert.doesNotMatch(texto, new RegExp(`OS #${fixture.ordensA[2]}\\b`));
    cp.execFileSync('docker', ['exec', '-e', 'PORTAL_MODE=entregar', container, 'php', '-d', 'variables_order=EGPCS', '/var/www/html/tests/Support/portal_cliente_publico.php'], { stdio: 'ignore' });
    await page.reload();
    texto = await page.locator('body').innerText();
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[2]}\\b`), 'new delivery updates the existing link');
    const novaOs = Number(cp.execFileSync('docker', ['exec', '-e', 'PORTAL_MODE=nova-os', container, 'php', '-d', 'variables_order=EGPCS', '/var/www/html/tests/Support/portal_cliente_publico.php'], { encoding: 'utf8' }));
    assert.ok(novaOs > 0);
    await page.goto(`${base}/index.php/publico_cliente/index/${fixture.a}`);
    texto = await page.locator('body').innerText();
    assert.match(texto, new RegExp(`OS #${novaOs}\\b`), 'new order appears without issuing another link');
    assert.match(texto, /Equipamento novo sintetico/);
    cp.execFileSync('docker', ['exec', '-e', 'PORTAL_MODE=receber', container, 'php', '-d', 'variables_order=EGPCS', '/var/www/html/tests/Support/portal_cliente_publico.php'], { stdio: 'ignore' });
    await page.reload();
    texto = await page.locator('body').innerText();
    assert.match(texto, /R\$ 360,00/, 'new payment updates the existing link');
    assert.match(texto, /R\$ 240,00/, 'balance updates after payment');
    response = await page.goto(`${base}/index.php/publico_cliente/os/${fixture.a}/${fixture.ordensA[1]}`);
    texto = await page.locator('body').innerText();
    assert.match(texto, /Total cobrado/);
    assert.match(texto, /Aberta em\s+\d{2}\/\d{2}\/\d{4}/, 'order detail shows its opening date');
    assert.doesNotMatch(texto, /PRIVADO-ALFA/, 'order detail excludes private notes');
    assert.match(texto, /R\$ 200,00/);
    assert.match(texto, /Total pago/);
    assert.match(texto, /R\$ 50,00/);
    response = await page.goto(`${base}/index.php/publico_cliente/os/${fixture.a}/${fixture.ordensA[10]}`);
    assert.equal(response.status(), 200);
    texto = await page.locator('body').innerText();
    assert.match(texto, /Diagnóstico público sintético/);
    assert.match(texto, /Aguardando resposta/);
    assert.doesNotMatch(texto, /Trabalho aprovado|PRIVADO-ALFA/);
    if (process.env.PORTAL_SCREENSHOT_DIR) {
      const path = require('node:path');
      await page.screenshot({ path: path.join(process.env.PORTAL_SCREENSHOT_DIR, 'portal-detalhe-desktop.png') });
      const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 1 });
      const mobilePage = await mobile.newPage();
      assert.equal((await mobilePage.goto(`${base}/index.php/publico_cliente/os/${fixture.a}/${fixture.ordensA[10]}`)).status(), 200);
      assert.equal(await mobilePage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
      await mobilePage.screenshot({ path: path.join(process.env.PORTAL_SCREENSHOT_DIR, 'portal-detalhe-mobile.png') });
      await mobile.close();
    }
    response = await page.goto(`${base}/index.php/publico_cliente/os/${fixture.a}/${fixture.osB}`);
    assert.equal(response.status(), 404, 'other customer order is not accessible');
    response = await page.goto(`${base}/index.php/publico_cliente/os/${fixture.b}/${fixture.osB}`);
    assert.equal(response.status(), 200, 'owner can access the order');
    assert.doesNotMatch(await page.locator('body').innerText(), /PRIVADO-BETA/);
    const anexoUrl = (os, anexo) => `${base}/index.php/publico_cliente/anexo/${fixture.a}/${os}/${anexo}`;
    assert.equal((await context.request.get(anexoUrl(fixture.osA, fixture.anexos.publico))).status(), 200, 'published attachment is accessible');
    assert.equal((await context.request.get(anexoUrl(fixture.osA, fixture.anexos.privado))).status(), 404, 'unpublished attachment is denied');
    assert.equal((await context.request.get(anexoUrl(fixture.osB, fixture.anexos.outro))).status(), 404, 'other customer attachment is denied');
    assert.equal((await context.request.get(anexoUrl(fixture.osA, fixture.anexos.outro))).status(), 404, 'mismatched attachment is denied');
    assert.equal((await context.request.get(`${base}/index.php/publico/os/${fixture.tokenOs}`)).status(), 200, 'individual OS link remains valid');
    assert.equal((await context.request.get(`${base}/index.php/publico/anexo/${fixture.tokenOs}/${fixture.anexos.publico}`)).status(), 200, 'individual OS published attachment remains accessible');
    assert.equal((await context.request.get(`${base}/index.php/publico/anexo/${fixture.tokenOs}/${fixture.anexos.privado}`)).status(), 404, 'individual OS unpublished attachment remains private');
    const linksOs = Number(cp.execFileSync('docker', ['exec', '-e', 'PORTAL_MODE=contar-links-os', container, 'php', '-d', 'variables_order=EGPCS', '/var/www/html/tests/Support/portal_cliente_publico.php'], { encoding: 'utf8' }));
    assert.equal(linksOs, 1, 'customer portal did not create individual OS tokens');
    console.log('PASS customer link, ownership and private notes');
    response = await page.goto(`${base}/index.php/trifase_cliente/gerenciar/${fixture.clienteA}`);
    assert.match(page.url(), /\/login/, 'anonymous admin access must redirect to login');
    const creds = JSON.parse(cp.execFileSync('docker', ['exec', container, 'php', '-r', "echo file_get_contents('/lab/credentials.json');"], { encoding: 'utf8' }));
    await page.locator('[name=email]').fill(creds.email);
    await page.locator('[name=senha]').fill(creds.password);
    await Promise.all([page.waitForURL('**/mapos'), page.locator('button[type=submit]').click()]);
    response = await page.goto(`${base}/index.php/clientes/visualizar/${fixture.clienteA}`);
    assert.equal(response.status(), 200);
    assert.equal(await page.getByRole('link', { name: /link público do cliente/i }).count(), 1, 'customer record links to sharing controls');
    response = await page.goto(`${base}/index.php/trifase_cliente/gerenciar/${fixture.clienteA}`);
    assert.equal(response.status(), 200, 'authorized administrator can manage customer link');
    assert.match(await page.locator('body').innerText(), /Revogar acesso/i);
    await Promise.all([page.waitForURL('**/trifase_cliente/gerenciar/**'), page.getByRole('button', { name: /renovar link/i }).click()]);
    const novoUrl = await page.locator('#link-cliente-publico').inputValue();
    assert.notEqual(novoUrl, `${base}/index.php/publico_cliente/index/${fixture.a}`);
    const oldResponse = await context.request.get(`${base}/index.php/publico_cliente/index/${fixture.a}`);
    assert.equal(oldResponse.status(), 404, 'renewal immediately invalidates prior link');
    await Promise.all([page.waitForURL('**/trifase_cliente/gerenciar/**'), page.getByRole('button', { name: /revogar acesso/i }).click()]);
    const revokedResponse = await context.request.get(novoUrl);
    assert.equal(revokedResponse.status(), 404, 'revocation immediately invalidates renewed link');
    const otherResponse = await context.request.get(`${base}/index.php/publico_cliente/index/${fixture.b}`);
    assert.equal(otherResponse.status(), 200, 'revocation does not affect another customer');
    cp.execFileSync('docker', ['exec', '-e', 'PORTAL_MODE=expirar', container, 'php', '-d', 'variables_order=EGPCS', '/var/www/html/tests/Support/portal_cliente_publico.php'], { stdio: 'ignore' });
    const expired = await context.request.get(`${base}/index.php/publico_cliente/index/${fixture.b}`);
    assert.equal(expired.status(), 404, 'expired token is denied');
    assert.match(expired.headers()['cache-control'] || '', /no-store/i);
    assert.equal(expired.headers()['referrer-policy'], 'no-referrer');
    const restritoContext = await browser.newContext();
    const restritoPage = await restritoContext.newPage();
    await restritoPage.goto(`${base}/index.php/login`);
    await restritoPage.locator('[name=email]').fill(fixture.restrito.email);
    await restritoPage.locator('[name=senha]').fill(fixture.restrito.senha);
    await Promise.all([restritoPage.waitForURL('**/mapos'), restritoPage.locator('button[type=submit]').click()]);
    const negado = await restritoContext.request.get(`${base}/index.php/trifase_cliente/gerenciar/${fixture.clienteA}`, { headers: { 'X-Requested-With': 'XMLHttpRequest' } });
    assert.equal(negado.status(), 403, 'authenticated operator without sharing permissions denied');
    await restritoContext.close();
    console.log('PASS admin login, restricted permission, renewal and revocation');
    const clientContext = await browser.newContext();
    const clientPage = await clientContext.newPage();
    await clientPage.goto(`${base}/index.php/mine`);
    await clientPage.locator('[name=email]').fill(fixture.emailCliente);
    await clientPage.locator('[name=senha]').fill(fixture.senhaCliente);
    await Promise.all([clientPage.waitForURL('**/mine/painel'), clientPage.locator('button[type=submit]').click()]);
    texto = await clientPage.locator('body').innerText();
    for (const valor of ['R$ 600,00', 'R$ 360,00', 'R$ 240,00']) assert.ok(texto.includes(valor), 'dashboard consolidates all formalized orders');
    assert.match(texto, /Entregue/i, 'dashboard shows effective delivery');
    await clientPage.goto(`${base}/index.php/mine/os`);
    assert.match(await clientPage.locator('body').innerText(), /Entregue/i, 'authenticated list exposes effective delivery');
    assert.match(await clientPage.locator('body').innerText(), /Saldo a pagar/i, 'authenticated list exposes consolidated balance');
    assert.match(await clientPage.locator('body').innerText(), /Não entregues/i, 'authenticated list provides delivery filter');
    texto = await clientPage.locator('body').innerText();
    for (const valor of ['R$ 600,00', 'R$ 360,00', 'R$ 240,00']) assert.ok(texto.includes(valor), 'consolidated values include all pages');
    await clientPage.goto(`${base}/index.php/mine/os/10`);
    texto = await clientPage.locator('body').innerText();
    assert.ok(texto.includes('R$ 240,00'), 'balance is independent of pagination');
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[0]}\\b`));
    await clientPage.goto(`${base}/index.php/mine/os?filtro=entregue`);
    texto = await clientPage.locator('body').innerText();
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[1]}\\b`));
    assert.match(texto, new RegExp(`OS #${fixture.ordensA[2]}\\b`), 'authenticated list reflects new delivery');
    console.log('PASS authenticated customer order list');
    await clientContext.close();
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error.message); process.exitCode = 1; });
